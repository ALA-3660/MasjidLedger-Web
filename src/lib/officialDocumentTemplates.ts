/**
 * Replace placeholders in template text
 */
export function populateTemplate(
  templateStr: string,
  data: Record<string, string | number | undefined>
): string {
  let result = templateStr;
  for (const [key, value] of Object.entries(data)) {
    if (value !== undefined && value !== null) {
      const regex = new RegExp(key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g');
      result = result.replace(regex, String(value));
    }
  }
  return result;
}

/**
 * Document Number Generators
 */
export function generateDefaultDocNumber(
  docType: OfficialDocumentType,
  year: number = new Date().getFullYear(),
  serial: number = 1
): string {
  const serialStr = String(serial).padStart(3, '0');
  switch (docType) {
    case 'NOTICE':
      return `নোটিশ/${year}/${serialStr}`;
    case 'APPLICATION':
      return `আবেদন/${year}/${serialStr}`;
    case 'ANNOUNCEMENT':
      return `ঘোষণা/${year}/${serialStr}`;
    case 'OUTGOING_LETTER':
      return `স্মারক/${year}/${serialStr}`;
    case 'INCOMING_LETTER':
      return `প্রাপ্তি/${year}/${serialStr}`;
    case 'OFFICE_ORDER':
      return `অফিস/${year}/${serialStr}`;
    case 'CERTIFICATE':
      return `সনদ/${year}/${serialStr}`;
    case 'RECOMMENDATION':
      return `সুপারিশ/${year}/${serialStr}`;
    case 'MEMO_REGISTER':
      return `রেজি/${year}/${serialStr}`;
    default:
      return `নথি/${year}/${serialStr}`;
  }
}
